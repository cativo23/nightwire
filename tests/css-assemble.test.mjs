import { test } from 'node:test';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { assemble, HEADER } from '../scripts/lib/css.mjs';

const dir = (name) => fileURLToPath(new URL(`./fixtures/css/${name}/`, import.meta.url));
const ok = () => assemble(`${dir('ok')}index.css`, { root: dir('ok') });

test('the generated header comes first', () => {
  assert.ok(ok().startsWith(`${HEADER}\n`));
  assert.match(HEADER, /^\/\* GENERATED by scripts\/build-css\.mjs from src\/ .* \*\/$/);
});

test('imports are inlined in manifest order, nested imports included', () => {
  const out = ok();
  const order = ['--x: 1', '.a {', '.c {', '.b {'].map((s) => out.indexOf(s));
  assert.ok(order.every((i) => i > 0), 'every rule is present');
  assert.deepEqual([...order].sort((a, b) => a - b), order);
});

test('each inlined file gets a src banner, and manifest comments are kept in place', () => {
  const out = ok();
  for (const rel of ['gen.css', 'a.css', 'sub/b.css', 'sub/c.css']) {
    assert.match(out, new RegExp(`^/\\* ── ${rel.replace('/', '\\/')} ─+ \\*/$`, 'm'), `banner for ${rel}`);
  }
  assert.ok(out.indexOf('/* Fixture manifest') < out.indexOf('── gen.css'));
  assert.ok(out.indexOf('── a.css') < out.indexOf('/* second group */'));
  assert.ok(out.indexOf('/* second group */') < out.indexOf('── sub/b.css'));
});

test('a GENERATED header line in an inlined file is dropped', () => {
  assert.doesNotMatch(ok(), /some\/script\.mjs/);
});

test('output is exact: banners, one blank line between pieces, trailing blank lines trimmed', () => {
  const banner = (rel) => `/* ── ${rel} ${'─'.repeat(Math.max(3, 60 - rel.length))} */`;
  assert.equal(ok(), [
    HEADER,
    '/* Fixture manifest\n   spans two lines */',
    '',
    banner('gen.css'),
    ':root { --x: 1; }',
    '',
    banner('a.css'),
    '.a { color: red; }',
    '',
    '/* second group */',
    '',
    banner('sub/b.css'),
    banner('sub/c.css'),
    '.c { color: green; }',
    '.b { color: blue; }',
    '',
  ].join('\n'));
});

test('output is LF-only and deterministic', () => {
  const a = ok();
  assert.equal(a, ok());
  assert.ok(!a.includes('\r'));
  assert.ok(a.endsWith('}\n') && !a.endsWith('\n\n'));
});

test('a manifest line that is neither an import nor a comment fails with its line number', () => {
  assert.throws(() => assemble(`${dir('bad')}not-import.css`, { root: dir('bad') }), /not-import\.css:2/);
});

test('a missing file fails and names its path', () => {
  assert.throws(() => assemble(`${dir('bad')}missing.css`, { root: dir('bad') }), /nope\.css/);
});

test('an import cycle fails and names the chain', () => {
  assert.throws(() => assemble(`${dir('bad')}cycle.css`, { root: dir('bad') }), /cycle-a\.css → cycle-b\.css → cycle-a\.css/);
});

test('a missing manifest fails and names it', () => {
  assert.throws(() => assemble(`${dir('bad')}nope-index.css`, { root: dir('bad') }), /nope-index\.css/);
});

test('an inlined file with an @import form the assembler does not inline fails', () => {
  assert.throws(() => assemble(`${dir('bad')}url-import.css`, { root: dir('bad') }), /url-import-target\.css:1/);
});

test('an @import line inside a block comment of an inlined file stays a comment', () => {
  const out = assemble(`${dir('ok')}commented.css`, { root: dir('ok') });
  assert.match(out, /\/\* old:\n@import "\.\/a\.css";\n\*\//);
  assert.equal(out.match(/\.a \{ color: red; \}/g)?.length ?? 0, 0);
});
