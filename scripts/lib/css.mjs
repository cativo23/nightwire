// Stylesheet assembly from an ordered manifest. Zero dependencies.
//
// assemble(entry, { root }) reads the manifest (src/index.css): only `@import "./x.css";` lines
// and comments are allowed there. Each import is inlined in order under a
// `/* ── <path from root> ── */` banner; manifest comments are kept in place; pieces are separated
// by one blank line. Inside an inlined file, a whole-line `@import` is replaced by that file's
// banner and content. A leading `/* GENERATED … */` line in an inlined file is dropped, since the
// assembled file carries its own header. No reformatting, no minification.

import { readFileSync, existsSync } from 'node:fs';
import { resolve, dirname, relative, sep } from 'node:path';

export const HEADER = '/* GENERATED by scripts/build-css.mjs from src/ — do not edit. Run `npm run build`. */';

const MANIFEST_TOKEN = /\s*(?:(\/\*[\s\S]*?\*\/)|@import\s+(["'])([^"']+)\2\s*;)/y;
const IMPORT_LINE = /^@import\s+(["'])([^"']+)\1\s*;\s*$/;

const toPosix = (p) => p.split(sep).join('/');
const banner = (rel) => `/* ── ${rel} ${'─'.repeat(Math.max(3, 60 - rel.length))} */`;

export function assemble(entry, { root }) {
  const rel = (file) => toPosix(relative(root, file));

  const read = (file, chain) => {
    if (chain.includes(file)) throw new Error(`import cycle: ${[...chain, file].map(rel).join(' → ')}`);
    if (!existsSync(file)) {
      throw new Error(chain.length ? `${rel(chain.at(-1))}: imported file not found: ${rel(file)}` : `manifest not found: ${rel(file)}`);
    }
    return readFileSync(file, 'utf8').replace(/\r\n?/g, '\n');
  };

  const inline = (file, chain) => {
    const text = read(file, chain);
    const lines = text.split('\n');
    const skipped = lines[0]?.startsWith('/* GENERATED') ? 1 : 0;
    if (skipped) lines.shift();
    const out = [];
    let inComment = false;
    lines.forEach((line, n) => {
      const m = !inComment && line.match(IMPORT_LINE);
      if (m) {
        out.push(inline(resolve(dirname(file), m[2]), [...chain, file]));
      } else {
        if (!inComment && /^\s*@import\b/.test(line)) {
          throw new Error(`${rel(file)}:${n + 1 + skipped}: only whole-line @import "./file.css"; is supported`);
        }
        out.push(line);
      }
      // Track block comments so an @import inside one stays text.
      for (const tok of line.match(/\/\*|\*\//g) ?? []) inComment = tok === '/*';
    });
    return `${banner(rel(file))}\n${out.join('\n').replace(/\n+$/, '')}`;
  };

  const manifest = read(entry, []);
  const pieces = [];
  MANIFEST_TOKEN.lastIndex = 0;
  let pos = 0;
  while (pos < manifest.length) {
    if (/^\s*$/.test(manifest.slice(pos))) break;
    MANIFEST_TOKEN.lastIndex = pos;
    const m = MANIFEST_TOKEN.exec(manifest);
    if (!m) {
      const at = pos + manifest.slice(pos).search(/\S/);
      const line = manifest.slice(0, at).split('\n').length;
      throw new Error(`${rel(entry)}:${line}: only @import "./file.css"; lines and comments are allowed in the manifest`);
    }
    pieces.push(m[1] ?? inline(resolve(dirname(entry), m[3]), [entry]));
    pos = MANIFEST_TOKEN.lastIndex;
  }
  return `${HEADER}\n${pieces.join('\n\n')}\n`;
}
