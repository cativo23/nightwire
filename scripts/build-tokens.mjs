#!/usr/bin/env node
// src/tokens/tokens.json → src/tokens/tokens.css, tailwind.preset.js, DESIGN.md token regions.
// Usage: npm run build:tokens   (exit 1 with a message naming the token or marker on error)

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { emitCss, emitPreset } from './lib/tokens.mjs';
import { emitRegions, rewrite } from './lib/designmd.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE = 'src/tokens/tokens.json';
const HEADER = `/* GENERATED by scripts/build-tokens.mjs from ${SOURCE} — do not edit. Run \`npm run build\`. */\n`;

function write(rel, content) {
  const path = resolve(ROOT, rel);
  if (existsSync(path) && readFileSync(path, 'utf8') === content) return false;
  writeFileSync(path, content);
  return true;
}

try {
  let tree;
  try {
    tree = JSON.parse(readFileSync(resolve(ROOT, SOURCE), 'utf8'));
  } catch (err) {
    throw new Error(`${SOURCE}: ${err.message}`);
  }
  const css = HEADER + emitCss(tree);
  const preset = HEADER + emitPreset(tree);
  const design = rewrite(readFileSync(resolve(ROOT, 'DESIGN.md'), 'utf8'), emitRegions(tree));
  const changed = [
    ['src/tokens/tokens.css', css],
    ['tailwind.preset.js', preset],
    ['DESIGN.md', design],
  ].filter(([rel, content]) => write(rel, content)).map(([rel]) => rel);
  console.log(`build:tokens  ${changed.length ? `wrote ${changed.join(', ')}` : 'up to date'}`);
} catch (err) {
  console.error(`build:tokens: ${err.message}`);
  process.exit(1);
}
